BEGIN;

CREATE TABLE IF NOT EXISTS chat_sessions (
    id UUID PRIMARY KEY,
    hf_user_id VARCHAR(255) NOT NULL,
    hf_username VARCHAR(255) NOT NULL,
    title VARCHAR(80) NOT NULL DEFAULT 'New chat',
    title_status VARCHAR(24) NOT NULL DEFAULT 'pending',
    title_source VARCHAR(24),
    title_generation_id UUID,
    title_prompt_revision INTEGER,
    title_model VARCHAR(255),
    title_generated_at TIMESTAMPTZ,
    selected_model VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    archived_at TIMESTAMPTZ,
    last_sequence INTEGER NOT NULL DEFAULT 0,
    message_count INTEGER NOT NULL DEFAULT 0,
    active_turn_id UUID,
    active_turn_expires_at TIMESTAMPTZ,
    sdk_session_id UUID UNIQUE,
    sdk_project_key TEXT,
    transcript_status VARCHAR(24) NOT NULL DEFAULT 'pending',
    transcript_bytes BIGINT NOT NULL DEFAULT 0,
    projection_bytes BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_chat_sessions_owner_updated ON chat_sessions (hf_user_id, updated_at DESC, id DESC);
ALTER TABLE chat_sessions
    ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_chat_sessions_owner_active_updated
    ON chat_sessions (hf_user_id, updated_at DESC, id DESC)
    WHERE archived_at IS NULL;

CREATE TABLE IF NOT EXISTS chat_messages (
    id UUID PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES chat_sessions(id) ON DELETE CASCADE,
    turn_id UUID NOT NULL,
    sequence INTEGER NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    client_message_id VARCHAR(200),
    revision INTEGER NOT NULL DEFAULT 1,
    supersedes_message_id UUID REFERENCES chat_messages(id) ON DELETE SET NULL,
    sdk_resume_boundary_id UUID,
    citations JSONB NOT NULL DEFAULT '[]'::jsonb,
    followups JSONB NOT NULL DEFAULT '[]'::jsonb,
    display_blocks JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(24) NOT NULL,
    model VARCHAR(255),
    model_route VARCHAR(255),
    error_code VARCHAR(64),
    prepared_fork_sdk_session_id UUID,
    prepared_fork_sdk_project_key TEXT,
    attempt_count INTEGER NOT NULL DEFAULT 1,
    last_attempted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_chat_messages_session_sequence UNIQUE (session_id, sequence),
    CONSTRAINT chat_messages_prepared_fork_pair_check CHECK (
        (prepared_fork_sdk_session_id IS NULL)
        = (prepared_fork_sdk_project_key IS NULL)
    )
);
CREATE INDEX IF NOT EXISTS idx_chat_messages_session_turn ON chat_messages (session_id, turn_id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_session_sequence ON chat_messages (session_id, sequence);
CREATE UNIQUE INDEX IF NOT EXISTS idx_chat_messages_client_id ON chat_messages (session_id, client_message_id) WHERE client_message_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_chat_messages_current_revision ON chat_messages (session_id, turn_id) WHERE role = 'user' AND status <> 'superseded';

-- Keep reruns corrective for databases that received the initial constraint
-- without an action. Session deletion must not depend on ORM row order when a
-- replacement message references its superseded revision.
ALTER TABLE chat_messages
    DROP CONSTRAINT IF EXISTS chat_messages_supersedes_message_id_fkey;
ALTER TABLE chat_messages
    ADD CONSTRAINT chat_messages_supersedes_message_id_fkey
    FOREIGN KEY (supersedes_message_id) REFERENCES chat_messages(id)
    ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS chat_sdk_transcript_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key TEXT NOT NULL,
    sdk_session_id UUID NOT NULL,
    subpath TEXT NOT NULL DEFAULT '',
    entry_uuid TEXT,
    entry JSONB NOT NULL,
    byte_size INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_chat_sdk_entries_load ON chat_sdk_transcript_entries (project_key, sdk_session_id, subpath, id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_chat_sdk_entries_uuid ON chat_sdk_transcript_entries (project_key, sdk_session_id, subpath, entry_uuid) WHERE entry_uuid IS NOT NULL;

CREATE TABLE IF NOT EXISTS chat_sdk_session_summaries (
    project_key TEXT NOT NULL,
    sdk_session_id UUID NOT NULL,
    mtime BIGINT NOT NULL,
    data JSONB NOT NULL,
    PRIMARY KEY (project_key, sdk_session_id)
);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'paperswithcode_user') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON chat_sessions, chat_messages,
            chat_sdk_transcript_entries, chat_sdk_session_summaries TO paperswithcode_user;
        GRANT USAGE, SELECT ON SEQUENCE chat_sdk_transcript_entries_id_seq
            TO paperswithcode_user;
    END IF;
END $$;

COMMIT;
